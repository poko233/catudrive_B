<?php

declare(strict_types=1);

namespace App\Shared\Traits;

trait GeneraUrlArchivo
{
    public function urlArchivo(
        ?string $ruta
    ): ?string {
        $ruta =
            trim(
                (string) $ruta
            );

        /*
        |--------------------------------------------------------------------------
        | RUTA VACÍA
        |--------------------------------------------------------------------------
        */

        if (
            $ruta === '' ||
            $ruta === '0' ||
            mb_strtolower(
                $ruta
            ) === 'null'
        ) {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | YA ES URL COMPLETA / DATA URI
        |--------------------------------------------------------------------------
        */

        if (
            str_starts_with(
                $ruta,
                'https://'
            ) ||
            str_starts_with(
                $ruta,
                'http://'
            ) ||
            str_starts_with(
                $ruta,
                'data:image/'
            )
        ) {
            return $ruta;
        }

        /*
        |--------------------------------------------------------------------------
        | BLOQUEAR ESQUEMAS DESCONOCIDOS
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/^[a-z][a-z0-9+.-]*:/i',
                $ruta
            ) === 1
        ) {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | NORMALIZAR RUTA
        |--------------------------------------------------------------------------
        */

        $rutaLimpia =
            ltrim(
                str_replace(
                    '\\',
                    '/',
                    $ruta
                ),
                '/'
            );

        /*
        |--------------------------------------------------------------------------
        | EVITAR PATH TRAVERSAL
        |--------------------------------------------------------------------------
        */

        $segmentos =
            explode(
                '/',
                $rutaLimpia
            );

        if (
            in_array(
                '..',
                $segmentos,
                true
            )
        ) {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | URL BASE DE ARCHIVOS
        |--------------------------------------------------------------------------
        |
        | LOCAL:
        |
        | FILES_URL=http://192.168.100.115:8000
        |
        | PRODUCCIÓN:
        |
        | FILES_URL=https://catudrive.metasoft-bolivia.com/api/public
        |
        |--------------------------------------------------------------------------
        */

        $base =
            rtrim(
                (string) config(
                    'app.files_url',
                    ''
                ),
                '/'
            );

        /*
        |--------------------------------------------------------------------------
        | FALLBACK
        |--------------------------------------------------------------------------
        */

        if (
            $base === ''
        ) {
            $base =
                rtrim(
                    (string) config(
                        'app.url',
                        ''
                    ),
                    '/'
                );
        }

        if (
            $base === ''
        ) {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | URL FINAL
        |--------------------------------------------------------------------------
        */

        return
            $base .
            '/' .
            $rutaLimpia;
    }
}